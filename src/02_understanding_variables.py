# Variables: guardan datos
nombre = "Emiliano"      # texto (string)
edad = 17               # número entero (int)
estatura = 1.65         # número con decimales (float)
es_estudiante = True     # verdadero o falso (bool)

print(nombre)
print(edad)
print(estatura)
print(es_estudiante)

# Cambiar el valor de una variable
edad = 20
print(edad)

# Ver el tipo de dato
print(type(nombre))
print(type(edad))